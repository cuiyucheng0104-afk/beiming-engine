S = 2


def build(n):
    W, H = 960 * S, 540 * S; d = np.zeros((H, W), np.float32)
    for kind, pts, val in LAYERS[n]:
        m = Image.new('L', (W, H), 0); ImageDraw.Draw(m).polygon([(x * S, y * S) for x, y in pts], fill=255); m = np.asarray(m) > 0
        if kind == G:
            ys = [p[1] * S for p in pts]; y0, y1 = min(ys), max(ys)
            g = np.clip((np.arange(H, dtype=np.float32)[:, None] - y0) / max(1, y1 - y0), 0, 1)
            v = np.broadcast_to(val[0] + (val[1] - val[0]) * g, (H, W))
        else:
            v = np.full((H, W), val, np.float32)
        d[m] = v[m]
    return gaussian_filter(d, 5)


def guided(I, p, r=24, eps=2e-3):
    f = lambda x: uniform_filter(x, 2 * r + 1, mode='nearest')
    mI, mp = f(I), f(p); a = (f(I * p) - mI * mp) / (f(I * I) - mI * mI + eps); b = mp - a * mI
    return f(a) * I + f(b)


def guess(a):
    """闪回图的自动深度：画面纵向位置 + 大气透视（远处淡、反差低）"""
    L = 0.3 * a[..., 0] + 0.59 * a[..., 1] + 0.11 * a[..., 2]; H, W = L.shape
    y = np.linspace(0, 1, H)[:, None].repeat(W, 1)
    mu = uniform_filter(L, 25); sd = np.sqrt(np.clip(uniform_filter(L * L, 25) - mu * mu, 0, None))
    haze = (1 - np.clip((mu - mu.min()) / (np.ptp(mu) + 1e-6), 0, 1)) * 0.6 + sd / (sd.max() + 1e-6) * 0.4
    d = 0.55 * y ** 1.3 + 0.45 * haze
    d = (d - d.min()) / (np.ptp(d) + 1e-6)
    return gaussian_filter(median_filter(d, 9), 6).astype(np.float32)


def main(sel, da=None):
    os.makedirs(OUT, exist_ok=True); os.makedirs(PRE, exist_ok=True)
    for n in sel:
        src = Image.open(f'{MAT}/image{n}.png').convert('RGB')
        small = np.asarray(src.resize((960, 540), Image.LANCZOS)).astype(np.float32) / 255
        I = 0.3 * small[..., 0] + 0.59 * small[..., 1] + 0.11 * small[..., 2]
        if n in LAYERS:
            p = np.asarray(Image.fromarray((build(n) * 255).astype(np.uint8)).resize((960, 540), Image.BILINEAR)).astype(np.float32) / 255
            if da and os.path.exists(f'{da}/image{n}.png'):
                q = np.asarray(Image.open(f'{da}/image{n}.png').convert('F').resize((960, 540), Image.BILINEAR))
                q = (q - q.min()) / (np.ptp(q) + 1e-6); p = 0.5 * p + 0.5 * q
                print('  融合 Depth Anything', n)
        else:
            p = guess(small)
        q = np.clip(guided(I, p), 0, 1)
        img = Image.fromarray((q * 255).astype(np.uint8)).resize((1920, 1080), Image.BILINEAR)
        img.save(f'{OUT}/d{n:02d}.png', optimize=True)
        # 对照图：左原图右深度
        cmp = Image.new('RGB', (960, 270)); cmp.paste(src.resize((480, 270)), (0, 0)); cmp.paste(img.convert('RGB').resize((480, 270)), (480, 0))
        cmp.save(f'{PRE}/d{n:02d}.jpg', quality=85)
        print('depth', n, flush=True)


