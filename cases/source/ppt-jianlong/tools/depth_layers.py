"""按画面手工分层的深度（Opus 读图推算）：坐标按 960×540 标注，0=最远 1=最近。
每层是一块多边形，按从远到近的顺序盖上去；地面层带纵向渐变；最后轻微羽化，避免推镜时撕裂。"""
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
S=2  # 标注坐标 ×2 = 1920×1080
LAYERS={
 'd19':[  # 龙山：天 → 龙首山体 → 雾带与中景林 → 前景树 → 人 → 脚下岩石
   ('poly',[(0,0),(960,0),(960,540),(0,540)],0.05),
   ('poly',[(400,0),(640,0),(700,90),(800,140),(960,180),(960,450),(0,450),(0,300),(150,230),(300,190),(390,120)],0.32),
   ('grad',[(0,360),(960,360),(960,540),(0,540)],(0.45,0.62)),
   ('poly',[(0,450),(130,440),(200,470),(240,540),(0,540)],0.78),
   ('poly',[(760,540),(800,470),(900,440),(960,430),(960,540)],0.78),
   ('poly',[(435,280),(470,278),(482,305),(495,370),(486,420),(490,478),(405,478),(410,370),(420,305)],0.9),
   ('poly',[(150,540),(250,490),(380,470),(460,455),(600,455),(680,490),(760,540)],0.97)],
 'd09':[  # 蛇颈山：远山 → 蛇兔山体 → 雾与瀑布 → 山路与登山者 → 左侧大树、前景枝叶
   ('poly',[(0,0),(960,0),(960,540),(0,540)],0.0),
   ('poly',[(370,60),(480,20),(600,40),(700,90),(800,120),(960,90),(960,330),(370,330)],0.25),
   ('grad',[(370,250),(960,250),(960,440),(370,440)],(0.38,0.55)),
   ('grad',[(0,260),(520,260),(560,540),(0,540)],(0.6,1.0)),
   ('poly',[(140,170),(250,160),(295,200),(290,330),(260,420),(230,485),(170,485),(150,330)],0.78),
   ('poly',[(310,165),(425,165),(425,200),(310,200)],0.76),
   ('poly',[(0,0),(200,0),(230,120),(200,300),(0,320)],0.85),
   ('poly',[(800,320),(900,300),(960,310),(960,540),(780,540)],0.9),
   ('poly',[(0,480),(960,470),(960,540),(0,540)],0.92)],
 'd01':[  # 鹿角岩：远山 → 中景山林 → 鹿角岩 → 人 → 左侧前景岩与枝叶、右下草坡
   ('poly',[(0,0),(960,0),(960,540),(0,540)],0.0),
   ('grad',[(0,140),(560,140),(560,420),(0,420)],(0.18,0.32)),
   ('poly',[(365,70),(455,15),(480,60),(560,100),(700,170),(760,190),(770,120),(720,110),(760,20),(860,40),(890,80),(880,280),(870,360),(560,380),(500,280),(420,160),(360,100)],0.5),
   ('poly',[(330,315),(360,310),(370,345),(378,420),(372,490),(308,490),(315,420),(318,345)],0.74),
   ('grad',[(0,220),(190,220),(200,540),(0,540)],(0.8,0.95)),
   ('grad',[(380,540),(380,450),(560,400),(880,330),(960,290),(960,540)],(0.72,1.0))],
}
def build(key):
    W,H=960*S,540*S; d=np.zeros((H,W),np.float32)
    for kind,pts,val in LAYERS[key]:
        m=Image.new('L',(W,H),0); ImageDraw.Draw(m).polygon([(x*S,y*S) for x,y in pts],fill=255); m=np.asarray(m)>0
        if kind=='grad':
            ys=[p[1]*S for p in pts]; y0,y1=min(ys),max(ys); g=np.linspace(0,1,H)[:,None]; g=np.clip((g*H-y0)/(y1-y0),0,1)
            v=val[0]+(val[1]-val[0])*np.broadcast_to(g,(H,W))
        else: v=np.full((H,W),val,np.float32)
        d[m]=v[m]
    img=Image.fromarray((d*255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(5))
    return np.asarray(img).astype(np.float32)/255
